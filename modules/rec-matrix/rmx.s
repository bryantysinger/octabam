| REC MATRIX, proof of concept: SRC3 = 10 (MTRX) records a sum of sources
| chosen per recorder, through stock's own SRC3 slot.
|
| Hooked at the recorder's SRC3 select inside the write path
| 0x400068e4(track, page, start, end) (docs/firmware/RECORDER.md section 2):
| stock sign-extends the SRC3 byte into d1, sends 0..7 (T1..T8) to the
| read-back block and 8..9 (MAIN, CUE) to 0x80005e60, then meets at
| 0x40007648 with the SRC3 pointer in d5. For 10 this stub fills one
| segment of a per-recorder block and points d5 at it; everything after
| (stock's SRC3 gain and FIN/FOUT ramp, INAB/INCD, the old-content path,
| stage 2's saturating sum, the pack) runs unchanged.
|
| Mixing rules (stock's own, docs: the INAB table at 0x80004808):
|   AB set           -> A left, B right, unity (the pair's A/B bits ignored)
|   A and B, no AB   -> 0.5 * (A + B) to both sides (stock's A+B entry)
|   A or B alone     -> that input to both sides, unity
|   the same for CD; T1..T8, MAIN, CUE -> stereo, unity
| The sum runs in 24-bit integers (each long's top 24 bits; the low byte,
| which carries junk on one core's read-back half, is dropped), so 16
| sources have headroom; the result saturates to 24 bits once, at the end.
|
| Mask bits: 0 A, 1 B, 2 C, 3 D, 4 AB, 5 CD, 6..13 T1..T8, 14 MAIN, 15 CUE.
| Each recorder's mask is a long behind rmx_mask_ptr (remix.inc, generated by
| the manifest): BRAIN's PROJECT setting REC<n>, loaded at each project load,
| or a constant when the image has no BRAIN.
|
| Two paths, the same result to the bit:
|   settled  every gain already sits on its target (no ramp running): the
|            usual case. Only the selected sources are touched, each in one
|            pass over the segment; the first pass stores (no clear), the
|            last one saturates as it adds (no separate pass). Gains on
|            their targets are 0, UNITY or HALF, so a source's share is
|            s >> 8, s >> 9 or nothing: no multiply.
|   ramping  for the 64 samples after a change: the general per-path ramp
|            loop (rmx_gain), as before, for all 18 paths.
| rmx_set holds, per recorder, the mask its gains settled on (-1 while a
| ramp runs). A new take snaps the gains to the mask's targets, so it starts
| settled.

        .equ    SEL_CONT,   0x400075E4      | stock: blts 0x40007600 (after cmpl d1,d4)
        .equ    MIX_CONT,   0x40007648      | stock: both pointer branches meet here
        .equ    RDBK_BASE,  0x80003190      | read-back block, half 0, T1
        .equ    RDBK_BANK,  0x800000E4      | the half the recorder and NEIGHBOR read
        .equ    MAINCUE,    0x80005E60      | MAIN at +0x00, CUE at +0x80
        .equ    SRC_MTRX,   10

| Gains: one long per path per recorder, Q15 (UNITY = 1.0), stepped toward
| the mask's target by STEP a sample, so a change ramps over RAMP samples
| instead of jumping. Paths: 0..7 A>L A>R B>L B>R C>L C>R D>L D>R (an input
| pair's four), 8..15 T1..T8, 16 MAIN, 17 CUE (stereo).
        .equ    UNITY,  32768
        .equ    HALF,   16384
        .equ    RAMP,   64                  | samples, about 1.5 ms
        .equ    STEP,   UNITY/RAMP
        .equ    NGAIN,  18
        .equ    GAP,    48                  | write-path calls, 16 a frame: three frames

| Quantized switching (QUANT.md): while the transport plays, a change to a
| recorder's stored mask takes over at once (QUANT OFF) or on the Nth
| boundary of the master grid after it (QUANT 1/2: half trigs; 1..4: trigs),
| on the sample stock's own arithmetic places an event there (0x4000aee0).
| Positions are stock's (1/tempo24 sample units, modulo 2^32). A transport
| restart while a change waits moves no target: one already passed commits
| at once, one ahead keeps its position.
        .equ    RUNNING,    0x800065B8      | long, 1 while the transport plays
        .equ    NEXTCLK,    0x4610757C      | the next 24 PPQN clock's position
        .equ    PHASE,      0x800065B6      | byte, that clock's index within the master step
        .equ    MSCALE,     0x8000663D      | byte, the master scale (CPS_TAB's index)
        .equ    CPS_TAB,    0x400ABA50      | clocks per step, a long per scale (6 at 1x)
        .equ    CLOCK,      2646000         | one 24 PPQN clock in position units
        .equ    FRAME_END,  0x46104CF0      | the end of the frame being written
        .equ    TINV,       0x80001820      | -2^31 / tempo24 (stock's 0x4000aee0 operand)

        .text

| Entry: the jmp written over stock's `mvsb d1,d1; moveq #7,d4; cmpl d1,d4`.
| Registers live into 0x40007648: a2 (AB pointer), d6 (CD pointer), fp;
| d5 is the output. d0-d4, d7, a0, a1, a3-a5 are rewritten there before use.
        .global rmx_select
rmx_select:
        mvs.b   %d1,%d1
        moveq   #SRC_MTRX,%d4
        cmp.l   %d4,%d1
        beq.s   .Lmtrx
        moveq   #7,%d4                      | displaced, replayed
        cmp.l   %d1,%d4                     | sets the flags stock's blts reads
        jmp     SEL_CONT

| The frame below: 0 d6, 4 a2 (live into MIX_CONT), 8 start, 12 count,
| 16 snap, 20 the second piece's mask, 24 the first piece's count (0: one
| piece), 28 MACSR, 32 ACC0.
.Lmtrx:
        move.l  136(%sp),%d0                | recorder 0..7 (the routine's first argument)
        move.l  144(%sp),%d4                | start sample
        move.l  48(%sp),%d7                 | d7 = sample count (end - start)
        lea     -36(%sp),%sp
        movem.l %d6/%a2,(%sp)
        move.l  %d0,rmx_cur
        move.l  %d4,8(%sp)
        move.l  %d7,12(%sp)
        clr.l   24(%sp)
        lea     rmx_mask_ptr,%a1
        move.l  (%a1,%d0.l*4),%a1
        move.l  (%a1),%d3
        and.l   #0xffff,%d3                 | d3 = this recorder's stored mask
        lea     rmx_last,%a0                | a new take (this recorder not mixed
        move.l  rmx_calls,%d1               | for GAP write-path calls) starts at
        move.l  (%a0,%d0.l*4),%d2           | the current selection: no ramp from
        move.l  %d1,(%a0,%d0.l*4)           | whatever was selected last time
        sub.l   %d2,%d1
        moveq   #0,%d5                      | d5 = snap the gains
        cmp.l   #GAP,%d1
        bls.s   0f
        moveq   #1,%d5
0:      move.l  %d5,16(%sp)

| ---- when the stored mask takes over -------------------------------------
| rmx_live is the mask the mixer uses. It becomes the stored mask at once on
| a new take or with the transport stopped; while playing, at the target:
| the next master step after the change, fixed when the change is first
| seen (later edits before it ride along). The target's sample in this
| frame is computed as stock's 0x4000aee0 computes its event bytes.
        lea     rmx_live,%a0
        lea     (%a0,%d0.l*4),%a0           | a0 = this recorder's live mask
        lea     rmx_pend,%a1
        lea     (%a1,%d0.l*4),%a1           | a1 = its pending flag
        tst.l   %d5
        bne.w   .Ladopt
        cmp.l   (%a0),%d3
        beq.w   .Lsame
        moveq   #1,%d1
        cmp.l   RUNNING,%d1
        bne.w   .Ladopt
        tst.l   (%a1)
        bne.w   .Lhave
        move.l  rmx_quant_ptr,%a5           | QUANT: 0 OFF, 1 half a trig,
        move.l  (%a5),%d4                   | 2..5 one to four trigs
        tst.l   %d4
        beq.w   .Ladopt
        mvz.b   PHASE,%d1                   | the next trig boundary: the next
        mvs.b   MSCALE,%d2                  | clock, plus the clocks from it to a
        lea     CPS_TAB,%a5                 | step start
        move.l  (%a5,%d2.l*4),%d6           | d6 = clocks per step
        move.l  %d6,%d2
        sub.l   %d1,%d2
        cmp.l   %d6,%d2
        blt.s   1f
        moveq   #0,%d2                      | phase 0: that clock starts a step
1:      move.l  #CLOCK,%d1
        muls.l  %d1,%d2
        add.l   NEXTCLK,%d2                 | d2 = the next trig boundary
        muls.l  %d1,%d6                     | d6 = a trig in position units
        subq.l  #1,%d4
        bne.s   2f
        lsr.l   #1,%d6                      | half a trig: the boundary half a
        move.l  %d2,%d1                     | trig before the next trig, if it is
        sub.l   %d6,%d1                     | still ahead of this frame's end
        move.l  %d1,%d4
        sub.l   FRAME_END,%d4
        ble.s   3f
        move.l  %d1,%d2
        bra.s   3f
2:      subq.l  #1,%d4                      | N trigs: the Nth trig boundary
        muls.l  %d4,%d6
        add.l   %d6,%d2
3:      lea     rmx_tgt,%a5
        move.l  %d2,(%a5,%d0.l*4)
        moveq   #1,%d1
        move.l  %d1,(%a1)
.Lhave: lea     rmx_tgt,%a5
        move.l  (%a5,%d0.l*4),%d1
        sub.l   FRAME_END,%d1               | d1 = target - frame end
        move.l  %macsr,%d2                  | stock's arithmetic, with its EMAC mode;
        move.l  %d2,28(%sp)                 | the write path's own state kept
        move.l  %acc0,%d2
        move.l  %d2,32(%sp)
        move.l  #32,%macsr
        move.l  #0,%acc0
        move.l  TINV,%d5
        msac.l  %d1,%d5,%acc0
        movclr.l %acc0,%d1
        add.l   #16,%d1                     | d1 = the target's sample in this frame
        move.l  32(%sp),%d2
        move.l  %d2,%acc0
        move.l  28(%sp),%d2
        move.l  %d2,%macsr
        move.l  8(%sp),%d2
        cmp.l   %d2,%d1
        ble.s   .Lnow                       | at or before this segment: from its start
        add.l   12(%sp),%d2
        cmp.l   %d2,%d1
        bge.s   .Lkeep                      | after it: not yet
        move.l  %d1,rmx_commit              | inside it: split there
        move.l  %d3,20(%sp)                 | the second piece's mask
        sub.l   8(%sp),%d1
        move.l  %d1,24(%sp)                 | the first piece's count
        clr.l   (%a1)
        move.l  %d3,%d1
        move.l  (%a0),%d3                   | the first piece: the old mask
        move.l  %d1,(%a0)
        bra.s   .Lmix
.Lnow:  move.l  8(%sp),%d1
        move.l  %d1,rmx_commit
        bra.s   .Ladopt
.Lsame: clr.l   (%a1)                       | edited back before its step
        bra.s   .Lmix
.Lkeep: move.l  (%a0),%d3
        bra.s   .Lmix
.Ladopt:
        move.l  %d3,(%a0)
        clr.l   (%a1)

.Lmix:  move.l  16(%sp),%d5
        move.l  8(%sp),%d4
        move.l  24(%sp),%d7
        bne.s   1f
        move.l  12(%sp),%d7                 | one piece: the whole segment
1:      move.l  (%sp),%d6
        move.l  4(%sp),%a2
        bsr.w   rmx_mix
        move.l  24(%sp),%d1
        beq.s   .Lend
        move.l  8(%sp),%d4                  | the second piece, from the commit
        add.l   %d1,%d4                     | sample, on the new mask: its gains
        move.l  12(%sp),%d7                 | ramp from there
        sub.l   %d1,%d7
        lsl.l   #3,%d1
        move.l  (%sp),%d6
        add.l   %d1,%d6
        move.l  4(%sp),%a2
        add.l   %d1,%a2
        move.l  20(%sp),%d3
        moveq   #0,%d5
        bsr.w   rmx_mix
.Lend:  move.l  rmx_cur,%d0                 | d5 = this recorder's block at the
        lsl.l   #7,%d0                      | call's start, as stock leaves it
        lea     rmx_buf,%a4
        add.l   %d0,%a4
        move.l  8(%sp),%d0
        lsl.l   #3,%d0
        add.l   %d0,%a4
        movem.l (%sp),%d6/%a2
        lea     36(%sp),%sp
        move.l  %a4,%d5
        jmp     MIX_CONT

| rmx_mix: one piece of a segment into this recorder's block. d3 = the mask,
| d4 = its start sample, d7 = its count, d5 = snap, a2 / d6 = the AB / CD
| segments at its start, rmx_cur = the recorder.
rmx_mix:
        move.l  rmx_cur,%d0
        moveq   #NGAIN*4,%d1
        muls.l  %d0,%d1
        lea     rmx_gains,%a5
        add.l   %d1,%a5                     | a5 = this recorder's gains
        lsl.l   #7,%d0
        lea     rmx_buf,%a4
        add.l   %d0,%a4                     | a4 = this recorder's 16-sample block
        lsl.l   #3,%d4                      | d4 = start * 8 (one stereo pair)
        add.l   %d4,%a4                     | a4 = this segment
        tst.l   %d7
        ble.w   .Ldone

        btst    #4,%d3                      | a stereo pair overrides its mono bits
        beq.s   1f
        and.l   #0xfffffffc,%d3
1:      btst    #5,%d3
        beq.s   2f
        and.l   #0xfffffff3,%d3
2:      move.l  rmx_cur,%d0
        lea     rmx_set,%a0
        lea     (%a0,%d0.l*4),%a0           | a0 = this recorder's settled mask
        tst.l   %d5
        bne.w   .Lsnap
        cmp.l   (%a0),%d3
        beq.w   .Lsettled

| ==== ramping: every path through rmx_gain =================================
        clr.l   rmx_moving
        move.l  %a4,%a1                     | clear the segment
        move.l  %d7,%d0
.Lclr:  clr.l   (%a1)+
        clr.l   (%a1)+
        subq.l  #1,%d0
        bgt.s   .Lclr
| ---- A / B: a2 = page + 0x80 + start*8, A at +0, B at +4 --------------------
        move.l  %a2,%a3
        move.l  %d3,%d0
        and.l   #3,%d0
        btst    #4,%d3
        beq.s   3f
        addq.l  #4,%d0
3:      lsl.l   #4,%d0
        lea     rmx_pair_tab,%a2
        add.l   %d0,%a2
        bsr.w   rmx_pair
| ---- C / D: d6 = page + start*8, C at +0, D at +4 ---------------------------
        move.l  %d6,%a3
        move.l  %d3,%d0
        lsr.l   #2,%d0
        and.l   #3,%d0
        btst    #5,%d3
        beq.s   4f
        addq.l  #4,%d0
4:      lsl.l   #4,%d0
        lea     rmx_pair_tab,%a2
        add.l   %d0,%a2
        lea     16(%a5),%a5
        bsr.w   rmx_pair
        lea     -16(%a5),%a5

| ---- T1..T8: 0x80003190 + bank*0x400 + k*0x80 + start*8 (stock's formula),
| then MAIN and CUE (0x80005e60 + start*8, +0x80): stereo, unity
        move.l  RDBK_BANK,%d0
        moveq   #10,%d1
        lsl.l   %d1,%d0
        add.l   #RDBK_BASE,%d0
        add.l   %d4,%d0
        move.l  %d0,%a2                     | a2 = T1's segment
        moveq   #6,%d2                      | d2 = the mask bit
        lea     32(%a5),%a0                 | a0 = T1's gain
.Ltr:   move.l  %a2,%a3
        moveq   #0,%d0
        btst    %d2,%d3
        beq.s   5f
        move.l  #UNITY,%d0
5:      move.l  %a4,%a1
        moveq   #0,%d1                      | stereo
        bsr.w   rmx_gain
        lea     0x80(%a2),%a2
        addq.l  #4,%a0
        addq.l  #1,%d2
        moveq   #14,%d0
        cmp.l   %d0,%d2
        blt.s   .Ltr
        move.l  #MAINCUE,%d0
        add.l   %d4,%d0
        move.l  %d0,%a2
.Lmc:   move.l  %a2,%a3                     | d2 = 14 MAIN, 15 CUE; a0 runs on
        moveq   #0,%d0
        btst    %d2,%d3
        beq.s   6f
        move.l  #UNITY,%d0
6:      move.l  %a4,%a1
        moveq   #0,%d1
        bsr.w   rmx_gain
        lea     0x80(%a2),%a2
        addq.l  #4,%a0
        addq.l  #1,%d2
        moveq   #16,%d0
        cmp.l   %d0,%d2
        blt.s   .Lmc

| ---- saturate to 24 bits and put each back in the top of its long ----------
        move.l  %a4,%a1
        move.l  %d7,%d0
        add.l   %d0,%d0                     | two longs a sample
.Lsat:  move.l  (%a1),%d1
        cmp.l   #0x007fffff,%d1
        ble.s   7f
        move.l  #0x007fffff,%d1
        bra.s   8f
7:      cmp.l   #0xff800000,%d1
        bge.s   8f
        move.l  #0xff800000,%d1
8:      lsl.l   #8,%d1
        move.l  %d1,(%a1)+
        subq.l  #1,%d0
        bgt.s   .Lsat

        move.l  rmx_cur,%d0                 | every gain on its target now:
        lea     rmx_set,%a0                 | settled on this mask
        moveq   #-1,%d1
        tst.l   rmx_moving
        bne.s   9f
        move.l  %d3,%d1
9:      move.l  %d1,(%a0,%d0.l*4)
        bra.w   .Ldone

| ==== a new take: every gain straight to its target, then settled ==========
.Lsnap: move.l  %d3,(%a0)
        move.l  %d3,%d0                     | A / B's four
        and.l   #3,%d0
        btst    #4,%d3
        beq.s   1f
        addq.l  #4,%d0
1:      lsl.l   #4,%d0
        lea     rmx_pair_tab,%a1
        add.l   %d0,%a1
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        move.l  %d3,%d0                     | C / D's four
        lsr.l   #2,%d0
        and.l   #3,%d0
        btst    #5,%d3
        beq.s   2f
        addq.l  #4,%d0
2:      lsl.l   #4,%d0
        lea     rmx_pair_tab,%a1
        add.l   %d0,%a1
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        move.l  (%a1)+,(%a5)+
        moveq   #6,%d2                      | T1..T8, MAIN, CUE
3:      moveq   #0,%d0
        btst    %d2,%d3
        beq.s   4f
        move.l  #UNITY,%d0
4:      move.l  %d0,(%a5)+
        addq.l  #1,%d2
        moveq   #16,%d0
        cmp.l   %d0,%d2
        blt.s   3b

| ==== settled: one pass per selected source ================================
| The list: per source its kind (0 stereo, 16 one input to both sides, 32
| an input pair folded at 0.5) and its segment. Then each pass, by kind and
| by mode (0 store, 4 store as the only one, 8 add, 12 add and saturate as
| the last one), from rmx_pass.
.Lsettled:
        lea     rmx_list,%a0
        move.l  %d3,%d0                     | A / B: a2 = its segment
        and.l   #3,%d0
        btst    #4,%d3
        beq.s   1f
        addq.l  #4,%d0
1:      lsl.l   #3,%d0
        lea     rmx_pair_kind,%a1
        add.l   %d0,%a1
        move.l  (%a1)+,%d0
        bmi.s   2f
        move.l  %d0,(%a0)+
        move.l  (%a1),%d0
        add.l   %a2,%d0
        move.l  %d0,(%a0)+
2:      move.l  %d3,%d0                     | C / D: d6 = its segment
        lsr.l   #2,%d0
        and.l   #3,%d0
        btst    #5,%d3
        beq.s   3f
        addq.l  #4,%d0
3:      lsl.l   #3,%d0
        lea     rmx_pair_kind,%a1
        add.l   %d0,%a1
        move.l  (%a1)+,%d0
        bmi.s   4f
        move.l  %d0,(%a0)+
        move.l  (%a1),%d0
        add.l   %d6,%d0
        move.l  %d0,(%a0)+
4:      move.l  %d3,%d0
        and.l   #0xffc0,%d0
        beq.w   .Lrun                       | no tracks, MAIN or CUE
        move.l  RDBK_BANK,%d0               | a1 = T1's segment (stock's formula)
        moveq   #10,%d1
        lsl.l   %d1,%d0
        add.l   #RDBK_BASE,%d0
        add.l   %d4,%d0
        move.l  %d0,%a1
        .irp    k,0,1,2,3,4,5,6,7
        btst    #6+\k,%d3
        beq.s   5f
        clr.l   (%a0)+
        lea     \k*0x80(%a1),%a3
        move.l  %a3,(%a0)+
5:
        .endr
        move.l  #MAINCUE,%d0
        add.l   %d4,%d0
        move.l  %d0,%a1
        .irp    k,0,1
        btst    #14+\k,%d3
        beq.s   6f
        clr.l   (%a0)+
        lea     \k*0x80(%a1),%a3
        move.l  %a3,(%a0)+
6:
        .endr

.Lrun:  move.l  %a0,%d2                     | d2 = the list's end
        lea     rmx_list,%a0
        cmp.l   %a0,%d2
        beq.s   .Lsilent
        moveq   #0,%d5                      | the first pass stores
.Lpass: move.l  (%a0)+,%d0
        move.l  (%a0)+,%a3
        add.l   %d5,%d0
        cmp.l   %a0,%d2
        bne.s   1f
        addq.l  #4,%d0                      | the last one saturates
1:      lea     rmx_pass,%a1
        move.l  (%a1,%d0.l),%a1
        move.l  %a4,%a5
        move.l  %d7,%d1
        jsr     (%a1)
        moveq   #8,%d5                      | the rest add
        cmp.l   %a0,%d2
        bne.s   .Lpass
        bra.s   .Ldone

.Lsilent:                                   | nothing selected: silence
        move.l  %a4,%a1
        move.l  %d7,%d0
1:      clr.l   (%a1)+
        clr.l   (%a1)+
        subq.l  #1,%d0
        bgt.s   1b

.Ldone: rts

| An input pair's targets (A>L, A>R, B>L, B>R) by (pair bit, B, A), stock's
| INAB rules: A alone or B alone to both sides, both folded at 0.5, the pair
| A left and B right.
        .balign 4
rmx_pair_tab:
        .long   0, 0, 0, 0
        .long   UNITY, UNITY, 0, 0
        .long   0, 0, UNITY, UNITY
        .long   HALF, HALF, HALF, HALF
        .long   UNITY, 0, 0, UNITY
        .long   UNITY, 0, 0, UNITY
        .long   UNITY, 0, 0, UNITY
        .long   UNITY, 0, 0, UNITY

| The same rows as a settled pass: its kind (-1 none) and where its input
| sits in the pair's segment.
rmx_pair_kind:
        .long   -1, 0                       | neither
        .long   16, 0                       | first alone, to both sides
        .long   16, 4                       | second alone, to both sides
        .long   32, 0                       | both, folded at 0.5
        .long   0, 0                        | the pair, stereo
        .long   0, 0
        .long   0, 0
        .long   0, 0

| One input pair: a3 = its segment (first input at +0, second at +4),
| a2 = its targets, a5 = its four gains, a4 = the output segment.
rmx_pair:
        move.l  %a5,%a0
        moveq   #1,%d1                      | one channel to one side
        move.l  %a4,%a1
        move.l  (%a2),%d0
        bsr.s   rmx_gain                    | A>L
        addq.l  #4,%a0
        moveq   #1,%d1
        lea     4(%a4),%a1
        move.l  4(%a2),%d0
        bsr.s   rmx_gain                    | A>R
        addq.l  #4,%a3
        addq.l  #4,%a0
        moveq   #1,%d1                      | one channel to one side
        move.l  %a4,%a1
        move.l  8(%a2),%d0
        bsr.s   rmx_gain                    | B>L
        addq.l  #4,%a0
        moveq   #1,%d1
        lea     4(%a4),%a1
        move.l  12(%a2),%d0
        bsr.s   rmx_gain                    | B>R
        subq.l  #4,%a3
        rts

| rmx_gain: add a source into the output at a gain ramped toward a target.
| a3 = source (stride 8), a1 = output (stride 8), a0 = the gain (updated),
| d0 = target, d5 = nonzero to snap to the target, d1 = 0 stereo (+0 to +0, +4 to +4) or 1 one channel (+0 to
| +0), d7 = count. Clobbers d0, d1, a1; keeps the rest. A gain left short
| of its target marks rmx_moving.
rmx_gain:
        lea     -24(%sp),%sp
        movem.l %d2-%d6/%a3,(%sp)
        move.l  (%a0),%d2                   | d2 = the gain now
        move.l  %d0,%d3                     | d3 = its target
        tst.l   %d5
        beq.s   0f
        move.l  %d3,%d2                     | a new take: straight to the target
0:
        move.l  %d1,%d6                     | d6 = the mode
        move.l  %d7,%d4                     | d4 = samples left
        cmp.l   %d2,%d3
        bne.s   .Lg_ramp
        tst.l   %d3
        beq.w   .Lg_out                     | off and staying off
        cmp.l   #UNITY,%d3
        bne.s   .Lg_ramp                    | a steady fraction: the general loop
.Lg_unity:                                  | steady unity: no multiply
        move.l  (%a3),%d0
        asr.l   #8,%d0
        add.l   %d0,(%a1)
        tst.l   %d6
        bne.s   1f
        move.l  4(%a3),%d0
        asr.l   #8,%d0
        add.l   %d0,4(%a1)
1:      addq.l  #8,%a3
        addq.l  #8,%a1
        subq.l  #1,%d4
        bgt.s   .Lg_unity
        bra.s   .Lg_out
.Lg_ramp:
        cmp.l   %d3,%d2                     | one step toward the target
        beq.s   3f
        blt.s   2f
        sub.l   #STEP,%d2
        cmp.l   %d3,%d2
        bge.s   3f
        move.l  %d3,%d2
        bra.s   3f
2:      add.l   #STEP,%d2
        cmp.l   %d3,%d2
        ble.s   3f
        move.l  %d3,%d2
3:      move.l  (%a3),%d0
        bsr.s   rmx_scale
        add.l   %d0,(%a1)
        tst.l   %d6
        bne.s   4f
        move.l  4(%a3),%d0
        bsr.s   rmx_scale
        add.l   %d0,4(%a1)
4:      addq.l  #8,%a3
        addq.l  #8,%a1
        subq.l  #1,%d4
        bgt.s   .Lg_ramp
.Lg_out:
        move.l  %d2,(%a0)
        cmp.l   %d2,%d3
        beq.s   5f
        moveq   #1,%d0
        move.l  %d0,rmx_moving
5:      movem.l (%sp),%d2-%d6/%a3
        lea     24(%sp),%sp
        rts

| d0 = (d0's top 24 bits) * d2 / UNITY, in two partial products so neither
| overflows. Clobbers d1, d5.
rmx_scale:
        asr.l   #8,%d0                      | s, 24 bits
        move.l  %d0,%d5
        asr.l   #8,%d5                      | its top 16 bits, signed
        and.l   #0xff,%d0                   | its low 8
        muls.l  %d2,%d5
        muls.l  %d2,%d0
        asr.l   #7,%d5
        moveq   #15,%d1
        asr.l   %d1,%d0
        add.l   %d5,%d0
        rts

| ---- settled passes -------------------------------------------------------
| a3 = the source's segment (stride 8), a5 = the output segment, d1 = count.
| May clobber d0, d1, d5, d6, a1, a3, a5. A gain on its target makes a
| source's share s >> 8 (UNITY) or s >> 9 (HALF), what rmx_scale gives for
| those gains. A single source is already within 24 bits (two halves too),
| so the only-one mode just drops the low byte: (s >> 8) << 8.

| d0 (left) and d6 (right) into the output, by mode.
        .macro  OUT_STORE
        move.l  %d0,(%a5)+
        move.l  %d6,(%a5)+
        .endm
        .macro  OUT_ADD
        add.l   %d0,(%a5)+
        add.l   %d6,(%a5)+
        .endm
        .macro  SAT1                        | d0 += out, to 24 bits, to the top
        add.l   (%a5),%d0
        cmp.l   %d5,%d0
        ble.s   1f
        move.l  %d5,%d0
1:      cmp.l   %a1,%d0
        bge.s   2f
        move.l  %a1,%d0
2:      lsl.l   #8,%d0
        move.l  %d0,(%a5)+
        .endm
        .macro  OUT_SAT
        SAT1
        move.l  %d6,%d0
        SAT1
        .endm
        .macro  SAT_CONSTS
        move.l  #0x007fffff,%d5
        move.l  #0xff800000,%d0
        move.l  %d0,%a1
        .endm

| the three kinds' shares into d0 / d6
        .macro  IN_STEREO
        move.l  (%a3)+,%d0
        asr.l   #8,%d0
        move.l  (%a3)+,%d6
        asr.l   #8,%d6
        .endm
        .macro  IN_DUP
        move.l  (%a3),%d0
        asr.l   #8,%d0
        move.l  %d0,%d6
        addq.l  #8,%a3
        .endm
        .macro  IN_FOLD
        move.l  (%a3),%d0
        asr.l   #8,%d0
        asr.l   #1,%d0
        move.l  4(%a3),%d6
        asr.l   #8,%d6
        asr.l   #1,%d6
        add.l   %d6,%d0
        move.l  %d0,%d6
        addq.l  #8,%a3
        .endm

        .macro  PASS in, out, consts=
        \consts
0:      \in
        \out
        subq.l  #1,%d1
        bgt.s   0b
        rts
        .endm
        .macro  ONLY in
0:      \in
        lsl.l   #8,%d0
        lsl.l   #8,%d6
        OUT_STORE
        subq.l  #1,%d1
        bgt.s   0b
        rts
        .endm

