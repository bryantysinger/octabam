        moveq   #SRC_MTRX+1,%d0             | the stored value (the runtime one is 10)
        cmp.l   8(%sp),%d0
        bne.s   .sf_stock
        lea     mtrx_label,%a0
        move.l  %a0,8(%sp)
        jmp     (0x40013a08).l              | sprintf(buf, "MTRX")
