rmx_fold_only:  ONLY    IN_FOLD
rmx_fold_add:   PASS    IN_FOLD, OUT_ADD
rmx_fold_sat:   PASS    IN_FOLD, OUT_SAT, SAT_CONSTS

        .balign 4
