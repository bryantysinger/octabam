src3_screen:
        move.l  (%sp)+,%d0                  | the return address
        move.l  %d4,(%sp)                   | displaced
        pea     src3_fmt                    | in place of the stock formatter
        move.l  %d0,-(%sp)
        rts

| fmt(buf, value): 11 -> "MTRX"; else the stock formatter (-, T1..T8, MAIN,
| CUE; stock prints CUE for anything above 10).
